def stable_seed(asset_id: str, version: str) -> int:
    digest = hashlib.sha256(f"{version}:{asset_id}".encode("utf-8")).digest()
    return int.from_bytes(digest[:4], "big") & 0x7FFFFFFF


def _asset(region: str, prompt: str, *, version: str) -> dict:
    asset_id = f"world.{region}.environment_master"
    return {
        "asset_id": asset_id,
        "region": region,
        "role": "environment_master",
        "preset": "plushbound_environment",
        "asset_class": "environment_master",
        "prompt": prompt,
        "seed": stable_seed(asset_id, version),
    }


def canary_assets(limit: int = MAX_CANARY_ASSETS) -> list[dict]:
    limit = int(limit)
    if not 1 <= limit <= MAX_CANARY_ASSETS:
        raise ValueError(f"bounded world canary limit must be between 1 and {MAX_CANARY_ASSETS}")
    rows = [_asset(region, prompt, version=CANARY_VERSION) for region, prompt in REGION_PROMPTS[:limit]]
    if len({row["asset_id"] for row in rows}) != len(rows):
        raise RuntimeError("duplicate world canary asset ID")
    return rows


def repair_assets() -> list[dict]:
    rows = [
        _asset(region, PROMPTS_BY_REGION[region] + NO_GLYPH_REPAIR_SUFFIX, version=REPAIR_VERSION)
        for region in REPAIR_REGIONS
    ]
    if len(rows) != MAX_REPAIR_ASSETS:
        raise RuntimeError("repair manifest must contain exactly six quarantined assets")
    if {row["region"] for row in rows} & ACCEPTED_CANARY_REGIONS:
        raise RuntimeError("repair manifest attempts to regenerate an accepted canary asset")
    if len({row["asset_id"] for row in rows}) != len(rows):
        raise RuntimeError("duplicate repair asset ID")
    return rows


def repair_v3_assets() -> list[dict]:
    rows = [
        _asset(region, REPAIR_V3_PROMPTS[region], version=REPAIR_V3_VERSION)
        for region in REPAIR_V3_REGIONS
    ]
    if len(rows) != MAX_REPAIR_V3_ASSETS:
        raise RuntimeError("repair-v3 manifest must contain exactly three quarantined assets")
    if {row["region"] for row in rows} & ACCEPTED_AFTER_V2_REGIONS:
        raise RuntimeError("repair-v3 manifest attempts to regenerate an accepted world asset")
    if {row["region"] for row in rows} != set(REPAIR_V3_REGIONS):
        raise RuntimeError("repair-v3 manifest differs from the three manually quarantined regions")
    if len({row["asset_id"] for row in rows}) != len(rows):
        raise RuntimeError("duplicate repair-v3 asset ID")
    return rows


@app.cls(
    gpu="L4",
    image=image,
    volumes={CACHE_DIR: model_cache},
    scaledown_window=120,
    timeout=1200,
)
class WorldMapFinalRunner:
    @modal.enter()
    def load(self):
        import torch
        from diffusers import DiffusionPipeline

        os.environ.setdefault("HF_HOME", CACHE_DIR)
        os.environ.setdefault("HF_HUB_CACHE", f"{CACHE_DIR}/hub")
        self.torch = torch
        self.pipe = DiffusionPipeline.from_pretrained(
            MODEL_ID,
            torch_dtype=torch.bfloat16,
            cache_dir=CACHE_DIR,
        )
        self.pipe.to("cuda")

    def _render(self, request: dict) -> tuple[bytes, float]:
        generator = self.torch.Generator(device="cuda").manual_seed(int(request["seed"]))
        started = time.monotonic()
        result = self.pipe(
            prompt=str(request["prompt"]),
            width=int(request["width"]),
            height=int(request["height"]),
            guidance_scale=float(request["guidance_scale"]),
            num_inference_steps=int(request["steps"]),
            generator=generator,
        ).images[0]
        elapsed = time.monotonic() - started
        out = io.BytesIO()
        result.save(out, format="PNG")
        return out.getvalue(), elapsed

    @modal.method()
    def run_assets(self, assets: list[dict], wave_mode: str) -> dict:
        from modal_worker.production_inspector import inspect_generation
        from modal_worker.production_request_builder import build_production_request
        from modal_worker.production_retry_policy import DEFAULT_PRODUCTION_RETRY_POLICY

        expected_caps = {
            "canary": MAX_CANARY_ASSETS,
            "repair-v2": MAX_REPAIR_ASSETS,
            "repair-v3": MAX_REPAIR_V3_ASSETS,
        }
        expected_cap = expected_caps.get(wave_mode, 0)
        if expected_cap == 0:
            raise RuntimeError(f"unsupported world production wave mode: {wave_mode}")
        if not 1 <= len(assets) <= expected_cap:
            raise RuntimeError(f"world {wave_mode} attempted {len(assets)} assets; hard cap is {expected_cap}")
        if len({str(item["asset_id"]) for item in assets}) != len(assets):
            raise RuntimeError("world bounded wave contains duplicate asset IDs")
        if wave_mode == "repair-v2" and {str(item["region"]) for item in assets} & ACCEPTED_CANARY_REGIONS:
            raise RuntimeError("repair-v2 attempted to regenerate a clean accepted canary region")
        if wave_mode == "repair-v3":
            regions = {str(item["region"]) for item in assets}
            if regions & ACCEPTED_AFTER_V2_REGIONS:
                raise RuntimeError("repair-v3 attempted to regenerate an accepted world region")
            if regions != set(REPAIR_V3_REGIONS):
                raise RuntimeError("repair-v3 attempted a region outside the exact three-item quarantine")

        retry = DEFAULT_PRODUCTION_RETRY_POLICY
        outputs = []
        total_gpu_seconds = 0.0
        started = time.monotonic()

        for item in assets:
            base_request = build_production_request(
                "plushbound_environment",
                str(item["prompt"]),
                seed=int(item["seed"]),
            )
            invariants = {
                "model_id": MODEL_ID,
                "renderer_route": "flux2_klein",
                "width": 1024,
                "height": 768,
                "steps": 4,
                "guidance_scale": 1.0,
                "bounded_production_authorized": True,
                "automatic_full_production_authorized": False,
                "catalog_wide_launch_authorized": False,
            }
            for key, expected in invariants.items():
                if base_request.get(key) != expected:
                    raise RuntimeError(
                        f"{item['asset_id']}: production request invariant {key}={base_request.get(key)!r} expected={expected!r}"
                    )

            accepted = False
            final = None
            for attempt in range(1, retry.max_attempts + 1):
                request = retry.variant(base_request, attempt)
                raw, elapsed = self._render(request)
                total_gpu_seconds += elapsed
                payload = {
                    "image_base64": base64.b64encode(raw).decode("ascii"),
                    "width": int(request["width"]),
                    "height": int(request["height"]),
                    "seed": int(request["seed"]),
                }
                inspection = inspect_generation(item, payload)
                final = {
                    "asset_id": item["asset_id"],
                    "region": item["region"],
                    "role": item["role"],
                    "preset": item["preset"],
                    "wave_mode": wave_mode,
                    "model_id": MODEL_ID,
                    "renderer_route": "flux2_klein",
                    "attempt": attempt,
                    "seed": int(request["seed"]),
                    "width": int(request["width"]),
                    "height": int(request["height"]),
                    "steps": int(request["steps"]),
                    "guidance_scale": float(request["guidance_scale"]),
                    "elapsed_seconds": round(elapsed, 3),
                    "sha256": hashlib.sha256(raw).hexdigest(),
                    "inspection": inspection,
                    "png_base64": payload["image_base64"],
                }
                if inspection["accepted"]:
                    accepted = True
                    break

            if final is None:
                raise RuntimeError(f"{item['asset_id']}: no generation attempt was made")
            final["accepted"] = accepted
            final["quarantined"] = not accepted
            outputs.append(final)

        accepted_count = sum(1 for row in outputs if row["accepted"])
        retry_generations = sum(max(0, int(row["attempt"]) - 1) for row in outputs)
        versions = {
            "canary": CANARY_VERSION,
            "repair-v2": REPAIR_VERSION,
            "repair-v3": REPAIR_V3_VERSION,
        }
        return {
            "schema": "plushbound.world_map_final_bounded_wave_report.v1",
            "version": versions[wave_mode],
            "wave_mode": wave_mode,
            "model": MODEL_ID,
            "gpu": "L4",
            "requested_count": len(assets),
            "accepted_count": accepted_count,
            "quarantined_count": len(outputs) - accepted_count,
            "retry_generations": retry_generations,
            "total_gpu_seconds": round(total_gpu_seconds, 3),
            "wall_seconds": round(time.monotonic() - started, 3),
            "bounded_production_authorized": True,
            "catalog_wide_launch_authorized": False,
            "outputs": outputs,
        }


@app.local_entrypoint()
def main(mode: str = "canary", limit: int = MAX_CANARY_ASSETS):
    mode = str(mode).strip().lower()
    if mode == "canary":
        assets = canary_assets(limit)
        output_dir = "world-map-final-canary"
    elif mode == "repair-v2":
        if int(limit) != MAX_REPAIR_ASSETS:
            raise RuntimeError(f"repair-v2 requires exact limit {MAX_REPAIR_ASSETS}")
        assets = repair_assets()
        output_dir = "world-map-final-repair-v2"
    elif mode == "repair-v3":
        if int(limit) != MAX_REPAIR_V3_ASSETS:
            raise RuntimeError(f"repair-v3 requires exact limit {MAX_REPAIR_V3_ASSETS}")
        assets = repair_v3_assets()
        output_dir = "world-map-final-repair-v3"
    else:
        raise RuntimeError(f"unsupported mode: {mode}")

    report = WorldMapFinalRunner().run_assets.remote(assets, mode)
    out_dir = Path(output_dir)
    out_dir.mkdir(exist_ok=True)
    manifest = []
    for item in report.pop("outputs"):
        encoded = item.pop("png_base64")
        raw = base64.b64decode(encoded)
        if hashlib.sha256(raw).hexdigest() != item["sha256"]:
            raise RuntimeError(f"{item['asset_id']}: local output hash mismatch")
        path = out_dir / f"{item['region']}-environment-master.png"
        path.write_bytes(raw)
        item["path"] = str(path)
        manifest.append(item)

    report["assets"] = manifest
    report_path = out_dir / "report.json"
    report_path.write_text(json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")
    print(json.dumps({k: v for k, v in report.items() if k != "assets"}, sort_keys=True))

    if report["quarantined_count"] != 0 or report["accepted_count"] != report["requested_count"]:
        raise RuntimeError(f"world {mode} did not pass deterministic production inspection; scaling is blocked")
